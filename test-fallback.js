#!/usr/bin/env node

const express = require('express');
const cors = require('cors');
const path = require('path');

// Import the creative fallback system
const { generateCreativeContent } = require('./backend/creative-fallback.js');

const app = express();
const PORT = 3001;

app.use(cors());
app.use(express.json());

// Simple website generation using fallback system
app.post('/api/generate', (req, res) => {
    const { prompt } = req.body;
    
    console.log(`Generating website for: "${prompt}"`);
    
    // Determine industry from prompt
    const lowerPrompt = prompt.toLowerCase();
    let industry = 'business'; // default
    
    if (lowerPrompt.includes('tech') || lowerPrompt.includes('startup') || lowerPrompt.includes('software')) {
        industry = 'technology';
    } else if (lowerPrompt.includes('restaurant') || lowerPrompt.includes('food') || lowerPrompt.includes('cafe')) {
        industry = 'restaurant';
    } else if (lowerPrompt.includes('health') || lowerPrompt.includes('medical') || lowerPrompt.includes('doctor')) {
        industry = 'healthcare';
    } else if (lowerPrompt.includes('education') || lowerPrompt.includes('school') || lowerPrompt.includes('learning')) {
        industry = 'education';
    }
    
    // Generate content using fallback system
    const content = generateCreativeContent(industry, prompt);
    
    // Create a simple HTML website
    const html = `
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${content.title}</title>
    <style>
        * { margin: 0; padding: 0; box-sizing: border-box; }
        body { font-family: 'Arial', sans-serif; line-height: 1.6; color: #333; }
        .container { max-width: 1200px; margin: 0 auto; padding: 0 20px; }
        header { background: linear-gradient(135deg, #667eea 0%, #764ba2 100%); color: white; padding: 2rem 0; }
        .hero { text-align: center; }
        .hero h1 { font-size: 3rem; margin-bottom: 1rem; }
        .hero p { font-size: 1.2rem; margin-bottom: 2rem; }
        .cta-button { display: inline-block; background: #ff6b6b; color: white; padding: 12px 30px; text-decoration: none; border-radius: 5px; font-weight: bold; }
        .features { padding: 4rem 0; background: #f8f9fa; }
        .features h2 { text-align: center; margin-bottom: 3rem; font-size: 2.5rem; }
        .feature-grid { display: grid; grid-template-columns: repeat(auto-fit, minmax(300px, 1fr)); gap: 2rem; }
        .feature-card { background: white; padding: 2rem; border-radius: 10px; box-shadow: 0 5px 15px rgba(0,0,0,0.1); }
        .feature-card h3 { color: #667eea; margin-bottom: 1rem; }
        footer { background: #333; color: white; text-align: center; padding: 2rem 0; }
    </style>
</head>
<body>
    <header>
        <div class="container">
            <div class="hero">
                <h1>${content.title}</h1>
                <p>${content.description}</p>
                <a href="#contact" class="cta-button">Get Started</a>
            </div>
        </div>
    </header>
    
    <section class="features">
        <div class="container">
            <h2>Our Services</h2>
            <div class="feature-grid">
                ${content.features.map(feature => `
                    <div class="feature-card">
                        <h3>${feature}</h3>
                        <p>Professional ${feature.toLowerCase()} services tailored to your needs.</p>
                    </div>
                `).join('')}
            </div>
        </div>
    </section>
    
    <footer>
        <div class="container">
            <p>&copy; 2024 ${content.title}. ${content.tagline}</p>
            <p>Generated by CloudIDE - No API key required!</p>
        </div>
    </footer>
</body>
</html>`;
    
    const result = {
        id: Date.now().toString(),
        html: html,
        title: content.title,
        description: content.description,
        industry: industry,
        timestamp: new Date().toISOString(),
        source: 'fallback-generator'
    };
    
    res.json(result);
});

app.get('/health', (req, res) => {
    res.json({ status: 'ok', message: 'CloudIDE Fallback Generator is running!' });
});

app.listen(PORT, () => {
    console.log(`🚀 CloudIDE Fallback Generator running on http://localhost:${PORT}`);
    console.log(`✅ No API key required - using built-in creative generator!`);
    console.log(`🧪 Test it: curl -X POST http://localhost:${PORT}/api/generate -H "Content-Type: application/json" -d '{"prompt": "Create a tech startup website"}'`);
});
